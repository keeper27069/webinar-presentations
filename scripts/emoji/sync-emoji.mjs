// Finds every emoji used in src/ and copies the matching Twemoji SVG into public/emoji/.
// Usage: node scripts/emoji/sync-emoji.mjs <path to twemoji assets/svg>
// Twemoji graphics © Twitter, Inc and other contributors, CC-BY 4.0 — https://github.com/jdecked/twemoji
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, copyFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';

const ROOT = new URL('../..', import.meta.url).pathname;
const svgDir = process.argv[2];
if (!svgDir || !existsSync(svgDir)) {
  console.error('usage: node scripts/emoji/sync-emoji.mjs <twemoji assets/svg dir>');
  process.exit(2);
}
const patternTs = readFileSync(path.join(ROOT, 'src/emoji/pattern.ts'), 'utf8');
const source = /String\.raw`([^`]+)`/.exec(patternTs)[1];
const re = new RegExp(source, 'gu');
const key = (s) => [...s].map((c) => c.codePointAt(0)).filter((cp) => cp !== 0xfe0f).map((cp) => cp.toString(16)).join('-');
const withFe0f = (s) => [...s].map((c) => c.codePointAt(0).toString(16)).join('-');

const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = path.join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(f) && !p.includes('/emoji/')) files.push(p);
  }
})(path.join(ROOT, 'src'));

const found = new Map();
for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(re)) found.set(key(m[0]), m[0]);

const available = new Set(readdirSync(svgDir).map((f) => f.replace(/\.svg$/, '')));
const out = path.join(ROOT, 'public/emoji');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const map = {};
const missing = [];
for (const [k, seq] of [...found].sort()) {
  const candidates = [k, withFe0f(seq), k.replace(/-1f3f[b-f]/g, '')];
  const file = candidates.find((c) => available.has(c));
  if (!file) { missing.push(seq); continue; }
  copyFileSync(path.join(svgDir, file + '.svg'), path.join(out, k + '.svg'));
  map[k] = 1;
}
writeFileSync(path.join(out, 'LICENSE.txt'),
  'Emoji graphics: Twemoji © Twitter, Inc and other contributors (https://github.com/jdecked/twemoji)\nLicensed under CC-BY 4.0: https://creativecommons.org/licenses/by/4.0/\n');
writeFileSync(path.join(ROOT, 'src/emoji/available.ts'),
  `// Generated by scripts/emoji/sync-emoji.mjs — emoji keys that have an SVG in public/emoji/\nexport const AVAILABLE = new Set<string>(${JSON.stringify(Object.keys(map))});\n`);
console.log(`${Object.keys(map).length} SVGs copied; ${missing.length} without an SVG: ${missing.join(' ')}`);
